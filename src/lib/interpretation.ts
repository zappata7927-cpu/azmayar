export interface InterpretationOutput {
  results: { analyte: AnalyteDef; value: number; result: AnalyteResult }[];
  patterns: PatternResult[];
  summary: string;
  overallSeverity: 0 | 1 | 2 | 3;
}

const SEVERITY_LABEL: Record<number, string> = {
  0: "همه مقادیر بررسی‌شده در محدوده مرجع هستند",
  1: "یک یا چند مقدار خفیف خارج از محدوده است؛ پیگیری ساده کافی است",
  2: "یافته‌هایی خارج از محدوده مشاهده شد که پیگیری پزشکی توصیه می‌شود",
  3: "یافته‌هایی با اولویت بالا وجود دارد؛ مشورت پزشکی با فوریت توصیه می‌شود",
};

export function interpretPanel(
  panel: PanelDef,
  values: Record<string, number>,
  sex: Sex,
  age?: number
): InterpretationOutput {
  const all: Record<string, number> = { ...values };
  if (age != null) all.age = age;
  const results: InterpretationOutput["results"] = [];
  const res = new Map<string, AnalyteResult>();
  for (const a of panel.analytes) {
    const v = values[a.key];
    if (v == null || Number.isNaN(v)) continue;
    const r = a.interpret(v, sex, all);
    results.push({ analyte: a, value: v, result: r });
    res.set(a.key, r);
  }
  const patterns = panel.patterns ? panel.patterns(all, sex, res) : [];
  const overall = Math.max(0, ...results.map((r) => r.result.severity), ...patterns.map((p) => p.severity)) as 0 | 1 | 2 | 3;
  return {
    results,
    patterns,
    summary: SEVERITY_LABEL[overall],
    overallSeverity: overall,
  };
}

