// Clinical interpretation engine — rule-based, educational, conservative.
// Thresholds follow widely accepted clinical references (ADA, ATP III/NCEP, KDIGO,
// WHO anemia criteria, ATA thyroid practice, standard clinical biochemistry textbooks
// such as Pagana & Pagana). Ranges may differ between laboratories; the app always
// reminds the user to confirm with their own lab reference and physician.

export type Sex = "male" | "female";

export type Status = "ok" | "low" | "high" | "critical-low" | "critical-high";

export interface AnalyteResult {
  status: Status;
  severity: 0 | 1 | 2 | 3; // 0 = normal, 3 = urgent
  title: string;
  detail: string;
  advice: string[];
}

export interface AnalyteDef {
  key: string;
  label: string;
  unit: string;
  required: boolean;
  sexSpecific?: boolean;
  refLabel: string; // displayed reference text
  interpret: (v: number, sex: Sex, all: Record<string, number>) => AnalyteResult;
}

export interface PatternResult {
  title: string;
  detail: string;
  severity: 1 | 2 | 3;
}

export interface PanelDef {
  key: string;
  title: string;
  desc: string;
  emoji: string;
  needSex?: boolean;
  needAge?: boolean;
  analytes: AnalyteDef[];
  patterns?: (v: Record<string, number>, sex: Sex, res: Map<string, AnalyteResult>) => PatternResult[];
}

const ok = (title: string, detail: string): AnalyteResult => ({ status: "ok", severity: 0, title, detail, advice: [] });

const mk = (
  status: Status,
  severity: 1 | 2 | 3,
  title: string,
  detail: string,
  advice: string[] = []
): AnalyteResult => ({ status, severity, title, detail, advice });

// ---------------- helpers ----------------
function r2(n: number): number {
  return Math.round(n * 10) / 10;
}

